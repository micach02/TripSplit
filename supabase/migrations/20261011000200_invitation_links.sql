-- =============================================================================
-- TripSplit · Invite links
--
-- Every invitation gets an unguessable token so the owner can send it through
-- Messenger, Viber, WhatsApp… without an email service. The link is the
-- credential: whoever opens it while signed in can join — like any invite
-- link. It works once, and expires with the invitation.
--
-- Email-based accept (get_my_invitations / accept_invitation) still works.
-- =============================================================================

alter table tripsplit.trip_invitations
  add column token uuid not null default gen_random_uuid();

create unique index trip_invitations_token_key on tripsplit.trip_invitations (token);

-- What an invite link shows before joining. Empty when the token is unknown.
create function tripsplit.get_invitation_preview(p_token uuid)
returns table (
  trip_id uuid,
  trip_name text,
  destination text,
  start_date date,
  end_date date,
  invited_by_name text,
  invited_by_avatar_url text,
  invited_name text,
  status text,
  already_member boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    i.trip_id,
    t.name,
    t.destination,
    t.start_date,
    t.end_date,
    p.full_name,
    p.avatar_url,
    i.invited_name,
    case
      when i.status = 'pending' and i.expires_at <= now() then 'expired'
      else i.status::text
    end,
    exists (
      select 1 from tripsplit.trip_members m
      where m.trip_id = i.trip_id and m.user_id = (select auth.uid())
    )
  from tripsplit.trip_invitations i
  join tripsplit.trips t on t.id = i.trip_id
  join tripsplit.profiles p on p.id = i.invited_by
  where i.token = p_token
    and (select auth.uid()) is not null;
$$;

-- Locks and validates a link invitation.
create function tripsplit_private.claim_invitation_link(p_token uuid)
returns tripsplit.trip_invitations
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_invitation tripsplit.trip_invitations;
begin
  if (select auth.uid()) is null then
    raise exception using errcode = '42501', message = 'not_authenticated';
  end if;

  select * into v_invitation from tripsplit.trip_invitations i where i.token = p_token for update;
  if not found then
    raise exception using errcode = 'P0001', message = 'invitation_not_found';
  end if;
  if v_invitation.status <> 'pending' then
    raise exception using errcode = 'P0001', message = 'invitation_not_pending';
  end if;
  if v_invitation.expires_at <= now() then
    raise exception using errcode = 'P0001', message = 'invitation_expired';
  end if;

  return v_invitation;
end;
$$;

-- Joins the trip through an invite link; returns the trip id.
create function tripsplit.accept_invitation_link(p_token uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_invitation tripsplit.trip_invitations;
begin
  -- Already on the trip (e.g. opened the link twice): just go there.
  select * into v_invitation from tripsplit.trip_invitations i where i.token = p_token;
  if found and exists (
    select 1 from tripsplit.trip_members m
    where m.trip_id = v_invitation.trip_id and m.user_id = (select auth.uid())
  ) then
    return v_invitation.trip_id;
  end if;

  v_invitation := tripsplit_private.claim_invitation_link(p_token);
  perform tripsplit.ensure_profile();

  insert into tripsplit.trip_members (trip_id, user_id, role)
  values (v_invitation.trip_id, (select auth.uid()), 'member')
  on conflict (trip_id, user_id) do nothing;

  update tripsplit.trip_invitations set status = 'accepted' where id = v_invitation.id;
  return v_invitation.trip_id;
end;
$$;

create function tripsplit.decline_invitation_link(p_token uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_invitation tripsplit.trip_invitations := tripsplit_private.claim_invitation_link(p_token);
begin
  update tripsplit.trip_invitations set status = 'declined' where id = v_invitation.id;
end;
$$;

revoke all on function
  tripsplit.get_invitation_preview(uuid),
  tripsplit_private.claim_invitation_link(uuid),
  tripsplit.accept_invitation_link(uuid),
  tripsplit.decline_invitation_link(uuid)
from public;

grant execute on function
  tripsplit.get_invitation_preview(uuid),
  tripsplit.accept_invitation_link(uuid),
  tripsplit.decline_invitation_link(uuid)
to authenticated, service_role;
grant execute on function tripsplit_private.claim_invitation_link(uuid) to service_role;

-- The token is generated by the database; clients never set or change it.
revoke update on tripsplit.trip_invitations from authenticated;
grant update (status, expires_at) on tripsplit.trip_invitations to authenticated;
